const enabled = () => lang() !== 'ru';
const col = () => (lang() === 'en' ? 1 : 2);
const map = new Map(WORDS.map(w => [w[0], w]));
const SKIP = '.cqa-bubble, .cqa-crit-why, .cqa-ex, .cqa-qa dd, .cqa-ap-comment, .cqa-ap-reason, .cqa-att-quote, input, textarea, script, style';

export function tr(text) {
  if (!enabled() || !text) return text;
  const key = text.trim();
  if (!key || !/[а-яё]/i.test(key)) return text;
  const hit = map.get(key);
  let out = hit ? hit[col()] : null;
  if (out == null) {
    for (const p of PATTERNS) {
      if (p[0].test(key)) { out = key.replace(p[0], p[col()]); break; }
    }
  }
  if (out == null) {
    out = key;
    for (const f of FRAGMENTS) out = out.replace(f[0], f[col()]);
  }
  if (out === key) return text;
  return text.replace(key, () => out);
}

function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const p = node.parentElement;
    if (!p || p.closest(SKIP)) return;
    const next = tr(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE || node.matches?.('script, style')) return;
  for (const a of ['title', 'placeholder', 'aria-label']) {
    const v = node.getAttribute(a);
    if (v) { const n = tr(v); if (n !== v) node.setAttribute(a, n); }
  }
  if (node.closest(SKIP) && !node.matches('input, textarea')) return;
  for (const c of node.childNodes) translateNode(c);
}

export function startI18n() {
  document.documentElement.lang = lang() === 'kk' ? 'kk' : lang();
  if (!enabled()) return;
  document.title = tr(document.title);
  translateNode(document.body);
  new MutationObserver(muts => {
    for (const m of muts) {
      if (m.type === 'characterData') translateNode(m.target);
      else if (m.type === 'attributes') translateNode(m.target);
      else m.addedNodes.forEach(translateNode);
    }
  }).observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['title', 'placeholder', 'aria-label'] });
}
